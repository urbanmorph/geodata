// Regenerates functions/lib/ward-bboxes.ts — the layer-level bounding boxes the
// locate endpoint uses to decide which city ward layer to auto-query for a point.
//
// Source of truth is each ward layer's PMTiles header bounds (tight, city-scale).
// Run this after adding, removing, or replacing any wards_* layer:
//
//     node scripts/gen-ward-bboxes.mjs
//
// It reads public/catalog.json for the wards_* layers + their PMTiles URLs, fetches
// each header, and writes a sorted Record<id, [west, south, east, north]>. If a ward
// layer is missing from the table at runtime it simply is not auto-included (safe
// degradation), so a forgotten regeneration never breaks locate — it just means a
// newly added city will not auto-resolve its ward until this is re-run.
import { PMTiles } from 'pmtiles';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const CATALOG = path.join(HERE, '..', 'public', 'catalog.json');
const OUT = path.join(HERE, '..', 'functions', 'lib', 'ward-bboxes.ts');

const catalog = JSON.parse(fs.readFileSync(CATALOG, 'utf8'));
const wards = (catalog.layers || [])
  .filter((l) => typeof l.id === 'string' && l.id.startsWith('wards_') && l.pmtiles?.url)
  .sort((a, b) => a.id.localeCompare(b.id));

if (!wards.length) {
  console.error('No wards_* layers with PMTiles found in catalog.json — aborting.');
  process.exit(1);
}

const round = (n) => Math.round(n * 1e6) / 1e6;
const entries = [];
for (const l of wards) {
  const h = await new PMTiles(l.pmtiles.url).getHeader();
  const bbox = [h.minLon, h.minLat, h.maxLon, h.maxLat].map(round);
  if (bbox.some((v) => !Number.isFinite(v)) || bbox[0] >= bbox[2] || bbox[1] >= bbox[3]) {
    console.error(`Bad bounds for ${l.id}: ${JSON.stringify(bbox)} — aborting.`);
    process.exit(1);
  }
  entries.push([l.id, bbox]);
  console.error(`  ${l.id.padEnd(26)} ${bbox.join(', ')}`);
}

const body = entries.map(([id, b]) => `  ${JSON.stringify(id)}: [${b.join(', ')}],`).join('\n');
const out = `// GENERATED by scripts/gen-ward-bboxes.mjs — do not edit by hand.
// Layer-level bounding boxes [west, south, east, north] for every wards_* layer,
// read from each layer's PMTiles header (tight, city-scale). The locate endpoint
// point-tests these to auto-include the ward layer(s) covering a query point.
// Regenerate after adding/removing/replacing a ward layer:
//     node scripts/gen-ward-bboxes.mjs
export type WardBbox = [west: number, south: number, east: number, north: number];

export const WARD_BBOXES: Record<string, WardBbox> = {
${body}
};
`;
fs.writeFileSync(OUT, out);
console.error(`\nWrote ${entries.length} ward bboxes -> ${path.relative(process.cwd(), OUT)}`);
